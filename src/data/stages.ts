function idify(text: string) {
  return text
    .toLowerCase()
    .replace(/\s+/g, '-')
    .replace(/[^\w\u4e00-\u9fa5/-]+/g, '')
}

function makeRole(title: string, stageName: string): Role {
  const department = roleDepartment[title] ?? '跨境业务团队'
  return {
    id: idify(title),
    title,
    department,
    description: `${title}负责${stageName}环节的执行、数据记录、异常处理和跨团队协作。`,
    responsibilities: [
      `完成${stageName}相关日常操作`,
      '维护关键业务数据和过程记录',
      '跟进异常问题并推动闭环',
      '沉淀可复用 SOP 和优化建议',
    ],
    kpis: ['处理时效', '准确率', '转化/履约质量', '异常闭环率'],
    painPoints: ['平台多、系统多，人工切换耗时', '数据分散在表格和后台', '异常依赖人工发现和追踪', '复盘难以沉淀为方法论'],
    tools: roleTools[title] ?? ['ERP', 'Excel', '平台后台', '协作文档'],
  }
}

function makeOpportunity(title: string, stageName: string, index: number) {
  const maturity: Array<'成熟' | '发展中' | '前沿'> = ['发展中', '成熟', '成熟', '前沿']
  const types: AIType[] = ['AI', 'RPA', 'Automation', 'Analytics']
  const difficulty: DifficultyLevel[] = ['low', 'medium', 'high']
  const impact: ImpactLevel[] = ['medium', 'high', 'high']
  return {
    id: idify(`${stageName}-${title}`),
    title,
    type: types[index % types.length],
    description: `围绕「${stageName}」场景，将人工导出、汇总、判断、提醒或内容生成动作自动化，减少重复劳动并提升经营响应速度。`,
    benefits: ['节省人工处理时间', '减少漏看和错填', '提高数据沉淀质量', '支持老板和运营快速复盘'],
    difficulty: difficulty[index % difficulty.length],
    impact: impact[index % impact.length],
    tools: ['RPA', 'AI 助手', 'BI 看板', '平台 API / 导出数据'],
    estimatedROI: index % 3 === 0 ? '1-3 个月可验证' : '3-6 个月可验证',
    maturity: maturity[index % maturity.length],
  }
}

